-- Forecast vs Actual
-- Paste into a Snowsight worksheet: each statement runs on its own.
-- Made-up demo data: on the demo database the table names have no prefix.

-- site_card
SELECT SITE_ID, REGION, DISTRICT, CITY, ADDRESS, TEAM_LEAD, TEAM_LEAD_EMAIL, PHONE, PLANNER, PLANNER_PHONE, DIRECTOR,
       SEGMENT, SIZE_BAND, OPENED_ON, SEATS, LAT, LON, NEW_FORECAST_SINCE
FROM DEMO.STAFFING.SITES
WHERE SITE_ID = 'S1022';

-- groups
SELECT DISTINCT QUEUE_GROUP
FROM DEMO.STAFFING.QUEUES
ORDER BY QUEUE_GROUP;

-- site_pulse
SELECT BIZ_DAY, OUTCOME, COUNT(*) AS LINES
FROM DEMO.STAFFING.PLAN_LINES
WHERE SITE_ID = 'S1022' AND BIZ_DAY BETWEEN '2000-01-01' AND '2026-11-06'
GROUP BY BIZ_DAY, OUTCOME
ORDER BY BIZ_DAY;

-- forecast_rows
SELECT D.BIZ_DAY, D.QUEUE_ID, I.NAME, I.SUBGROUP, D.FORECAST_FULL_DAY, D.HANDLED, D.ROSTERED_AM
FROM DEMO.STAFFING.DAILY D
JOIN DEMO.STAFFING.QUEUES I ON I.QUEUE_ID = D.QUEUE_ID
WHERE D.SITE_ID = 'S1022' AND I.QUEUE_GROUP = 'Claims' AND D.HAS_RUN = 1 AND D.BIZ_DAY BETWEEN '2026-09-08' AND '2026-11-06'
ORDER BY D.BIZ_DAY, D.QUEUE_ID;
